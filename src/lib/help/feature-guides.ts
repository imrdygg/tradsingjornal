/** The guide for a tab, falling back to the getting-started topic. */
export function guideFor(id: string): FeatureGuide {
  return (
    FEATURE_GUIDES.find((guide) => guide.id === id) ??
    FEATURE_GUIDES.find((guide) => guide.id === 'start')!
  );
}
