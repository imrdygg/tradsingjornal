/**
 * The in-app guide, one entry per screen.
 *
 * Every screen has a "what this is / how to use it / good to know" block, because a journal
 * that only its author can drive is a journal nobody keeps using. The steps name the controls
 * that are actually on the screen — a guide that says "configure your instruments" without
 * saying where is worse than no guide at all — and the notes say the limits plainly, including
 * which features need services the buyer supplies.
 *
 * Kept as data rather than JSX so the same content can be read by the panel, tested for
 * coverage, and later exported to a printable setup sheet without rewriting it.
 */

export type GuideTopic =
  | 'today'
  | 'trades'
  | 'mes'
  | 'analytics'
  | 'insights'
  | 'coach'
  | 'markets'
  | 'playbook'
  | 'memory'
  | 'history'
  | 'settings'
  | 'start';

export interface FeatureGuide {
  id: GuideTopic;
  label: string;
  title: string;
  summary: string;
  steps: string[];
  notes: string[];
  /** Services the buyer must supply before this screen is fully useful. */
  requires?: string[];
}

